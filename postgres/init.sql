CREATE TABLE IF NOT EXISTS persons (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(20)  NOT NULL,
    surname    VARCHAR(40)  NOT NULL,
    patronymic VARCHAR(40),
    birth_date DATE         NOT NULL,
    gender     VARCHAR(20),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS person_passports (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person_id INTEGER NOT NULL REFERENCES persons(id) ON DELETE CASCADE,
    passport_series VARCHAR(4) NOT NULL,
    passport_number VARCHAR(6) NOT NULL,
    issue_date DATE,
    division_code VARCHAR(7),
    issued_by TEXT,
    birth_place TEXT,
    registration TEXT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (passport_series, passport_number)
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_one_active_passport
    ON person_passports (person_id) WHERE active = TRUE;

CREATE TABLE IF NOT EXISTS requests (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person_id INTEGER REFERENCES persons(id) ON DELETE SET NULL,
    first_name VARCHAR(20),
    surname    VARCHAR(40),
    patronymic VARCHAR(40),
    mobile_phone VARCHAR(50),
    home_phone   VARCHAR(50),
    other_contact TEXT,
    email VARCHAR(150),
    gender VARCHAR(20),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_persons_match
    ON persons (lower(surname), lower(first_name), birth_date);